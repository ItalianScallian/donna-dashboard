export function getCardById(id: string): CreditCard | undefined {
  return CARDS.find((c) => c.id === id)
}

export function getCardByName(name: string): CreditCard | undefined {
  return CARDS.find(
    (c) => c.name.toLowerCase() === name.toLowerCase() || c.id === name
  )
}
